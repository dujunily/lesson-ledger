package cn.yiweiqiu.lessonledger.domain

import cn.yiweiqiu.lessonledger.core.Dates
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.LocalDate
import java.time.LocalTime

/**
 * 金额折算的回归测试。
 *
 * 重点是「待消耗金额不能超过实付总额」：曾经用「四舍五入后的单价 × 课时数」算，
 * 42 节课、单价 ¥71.43 会算出 ¥3000.06，比实付的 ¥3000 还多。
 */
class LedgerCalcTest {

    private fun course() = Course(
        id = "c1",
        childId = "k1",
        courseName = "羽毛球",
        orgName = "青羽体育",
        category = Category.SPORTS,
        teacher = null,
        location = null,
        weekdayMask = 0b0000100,
        startTime = "18:00",
        durationMinutes = 60,
        warningThreshold = 5,
        remindBeforeMinutes = 30,
        status = CourseStatus.ACTIVE,
        totalLessonsBoughtHalf = 84,
        note = "",
        createdAt = 0,
        updatedAt = 0,
        deleted = false,
    )

    private fun payment(amountCents: Long, totalHalf: Long) = Payment(
        id = "p1",
        courseId = "c1",
        payDate = LocalDate.of(2026, 10, 28),
        amountCents = amountCents,
        originalAmountCents = null,
        lessonsBoughtHalf = totalHalf,
        lessonsBonusHalf = 0,
        payMethod = PayMethod.WECHAT,
        validUntil = null,
        receipts = emptyList(),
        note = "",
        createdAt = 0,
        updatedAt = 0,
        deleted = false,
    )

    @Test
    fun `待消耗金额等于实付总额而不是略高`() {
        // 报名费 3000 元 / 42 节（买 40 送 2）
        val stats = LedgerCalc.computeStats(
            course = course(),
            payments = listOf(payment(amountCents = 300_000, totalHalf = 84)),
            lessons = emptyList(),
            today = LocalDate.of(2026, 10, 28),
            now = Dates.toMillis(LocalDate.of(2026, 10, 28), LocalTime.of(17, 0)),
        )
        assertEquals("待消耗金额必须正好是实付的 3000 元", 300_000L, stats.pendingValueCents)
        assertEquals("有效单价显示为 71.43 元/节", 7_143L, stats.unitPriceCents)
        assertTrue("待消耗不能超过实付", stats.pendingValueCents <= stats.paidCents)
    }

    @Test
    fun `上掉一部分课时后按比例折算`() {
        val used = Lesson(
            id = "l1",
            courseId = "c1",
            scheduledAt = Dates.toMillis(LocalDate.of(2026, 10, 20), LocalTime.of(18, 0)),
            actualAt = Dates.toMillis(LocalDate.of(2026, 10, 20), LocalTime.of(19, 0)),
            durationMinutes = 60,
            status = LessonStatus.DONE,
            deductedHalf = 20, // 上了 10 节
            paymentId = "p1",
            teacher = null,
            note = "",
            autoGenerated = true,
            suppressed = false,
            createdAt = 0,
            updatedAt = 0,
            deleted = false,
        )
        val stats = LedgerCalc.computeStats(
            course = course(),
            payments = listOf(payment(amountCents = 300_000, totalHalf = 84)),
            lessons = listOf(used),
            today = LocalDate.of(2026, 10, 28),
            now = Dates.toMillis(LocalDate.of(2026, 10, 28), LocalTime.of(17, 0)),
        )
        // 剩 32 节 = 64 半节 → 64 * 300000 / 84 = 228571.43 → 228571 分
        assertEquals(228_571L, stats.pendingValueCents)
        assertTrue(stats.pendingValueCents <= stats.paidCents)
    }

    @Test
    fun `赠送课时不会把待消耗金额撑大`() {
        // 买 40 节 3000 元，另外白送 2 节（独立批次）
        val bonus = payment(amountCents = 0, totalHalf = 4).copy(id = "p2")
        val stats = LedgerCalc.computeStats(
            course = course(),
            payments = listOf(payment(amountCents = 300_000, totalHalf = 80), bonus),
            lessons = emptyList(),
            today = LocalDate.of(2026, 10, 28),
            now = Dates.toMillis(LocalDate.of(2026, 10, 28), LocalTime.of(17, 0)),
        )
        assertEquals("赠送的课不额外产生价值", 300_000L, stats.pendingValueCents)
    }

    @Test
    fun `退费后待消耗金额跟着变小`() {
        // 先退 4 节（-8 半节、-30000 分）
        val refund = payment(amountCents = -30_000, totalHalf = -8).copy(id = "p2")
        val stats = LedgerCalc.computeStats(
            course = course(),
            payments = listOf(payment(amountCents = 300_000, totalHalf = 84), refund),
            lessons = emptyList(),
            today = LocalDate.of(2026, 10, 28),
            now = Dates.toMillis(LocalDate.of(2026, 10, 28), LocalTime.of(17, 0)),
        )
        // 退完还剩 38 节，实付净额 2700 元
        assertEquals(270_000L, stats.pendingValueCents)
        assertTrue(stats.pendingValueCents <= stats.paidCents)
    }

    @Test
    fun `定金加尾款被当成一个批次算单价`() {
        // 整期 3200 元买 42 节（84 半节）：定金实付 500、抵 800，尾款补 2400
        val deposit = Payment(
            id = "d1",
            courseId = "c1",
            payDate = LocalDate.of(2026, 10, 1),
            amountCents = 50_000,
            originalAmountCents = 320_000,
            lessonsBoughtHalf = 84,
            lessonsBonusHalf = 0,
            payMethod = PayMethod.WECHAT,
            validUntil = null,
            receipts = emptyList(),
            note = "定金",
            createdAt = 0,
            updatedAt = 0,
            deleted = false,
            kind = PaymentKind.DEPOSIT,
            creditCents = 80_000,
        )
        val balance = Payment(
            id = "b1",
            courseId = "c1",
            payDate = LocalDate.of(2026, 10, 20),
            amountCents = 240_000,
            originalAmountCents = null,
            lessonsBoughtHalf = 0,
            lessonsBonusHalf = 0,
            payMethod = PayMethod.WECHAT,
            validUntil = null,
            receipts = emptyList(),
            note = "尾款",
            createdAt = 1,
            updatedAt = 1,
            deleted = false,
            kind = PaymentKind.BALANCE,
            groupKey = "d1",
        )
        val stats = LedgerCalc.computeStats(
            course = course(),
            payments = listOf(deposit, balance),
            lessons = emptyList(),
            today = LocalDate.of(2026, 10, 28),
            now = Dates.toMillis(LocalDate.of(2026, 10, 28), LocalTime.of(17, 0)),
        )
        // 实付合计 2900 元，单价按整期 42 节摊 = ¥69.05/节
        assertEquals(290_000L, stats.paidCents)
        assertEquals(84L, stats.purchasedHalf)
        assertEquals(6_905L, stats.unitPriceCents)
        assertEquals(290_000L, stats.pendingValueCents)
        // 定金与尾款只算一个批次，金额是两笔之和
        assertEquals(1, stats.batches.size)
        assertEquals(84L, stats.batches.first().totalHalf)
        assertEquals(290_000L, stats.batches.first().amountCents)
    }

    @Test
    fun `只交了定金还没补尾款时能被找出来`() {
        val deposit = payment(amountCents = 50_000, totalHalf = 84).copy(
            id = "d1",
            originalAmountCents = 320_000,
            kind = PaymentKind.DEPOSIT,
            creditCents = 80_000,
        )
        val data = LedgerData(courses = listOf(course()), payments = listOf(deposit))
        assertEquals(1, data.pendingDeposits("c1").size)
        assertEquals(240_000L, data.pendingDeposits("c1").first().balanceDueCents)

        val paid = data.copy(
            payments = listOf(
                deposit,
                payment(amountCents = 240_000, totalHalf = 0).copy(
                    id = "b1",
                    kind = PaymentKind.BALANCE,
                    groupKey = "d1",
                ),
            ),
        )
        assertTrue("补完尾款就不再提示", paid.pendingDeposits("c1").isEmpty())
    }

    @Test
    fun `按实际时长折算扣课时`() {
        // 1 小时 = 1 课时，所以基准 60 分钟
        assertEquals("上满 60 分钟 = 1 节", 2L, LedgerCalc.deductedFromDuration(60, 60))
        assertEquals("上 90 分钟 = 1.5 节", 3L, LedgerCalc.deductedFromDuration(90, 60))
        assertEquals("上 2 小时 = 2 节", 4L, LedgerCalc.deductedFromDuration(120, 60))
        // 不足一整节往上补到 0.5 节，别把 45 分钟记成 0.5 节以下
        assertEquals("45 分钟取到 1 节", 2L, LedgerCalc.deductedFromDuration(45, 60))
        // 基准时长没填（0 / 负）时别除以零，按 60 兜底
        assertEquals(3L, LedgerCalc.deductedFromDuration(90, 0))
        // 再短也至少记 0.5 节，不能出现 0
        assertEquals(1L, LedgerCalc.deductedFromDuration(5, 60))
    }
}
