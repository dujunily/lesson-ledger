package cn.yiweiqiu.lessonledger.domain

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.LocalDate

/**
 * 两套数据「增删改互不影响」的底线。
 *
 * 归属判定只有一处（[LedgerData.forSource]），所有页面、统计、提醒、小组件、导出导入
 * 都从它这里取数。所以只要这组用例守住，在一套里怎么造都漏不到另一套。
 *
 * 这里刻意覆盖两类容易漏的情况：
 * 1. 记录 id 不带 `seed-` 前缀，但挂在演示的课程/孩子下面（核销记录就是这样）
 * 2. 在演示孩子名下新建的课，id 是普通 UUID
 */
class SourceIsolationTest {

    private fun child(id: String, name: String) = Child(
        id = id, name = name, nickname = "", birthday = null, avatarColor = "#000000",
        note = "", createdAt = 0L, updatedAt = 0L, deleted = false,
    )

    private fun course(id: String, childId: String, name: String = "课") = Course(
        id = id, childId = childId, orgName = "机构", courseName = name,
        category = Category.OTHER, teacher = null, location = null,
        weekdayMask = 1, startTime = "18:00", durationMinutes = 60,
        warningThreshold = 1, remindBeforeMinutes = 0, status = CourseStatus.ACTIVE,
        totalLessonsBoughtHalf = 0L, note = "", createdAt = 0L, updatedAt = 0L, deleted = false,
    )

    private fun payment(id: String, courseId: String) = Payment(
        id = id, courseId = courseId, payDate = LocalDate.of(2026, 1, 1),
        amountCents = 10_000L, originalAmountCents = null,
        lessonsBoughtHalf = 2L, lessonsBonusHalf = 0L, payMethod = PayMethod.OTHER,
        validUntil = null, receipts = emptyList(), note = "",
        createdAt = 0L, updatedAt = 0L, deleted = false,
    )

    private fun lesson(id: String, courseId: String, note: String = "") = Lesson(
        id = id, courseId = courseId, scheduledAt = 1L, actualAt = null, durationMinutes = 60,
        status = LessonStatus.PENDING, deductedHalf = 0L, paymentId = null, teacher = null,
        note = note, autoGenerated = true, suppressed = false,
        createdAt = 0L, updatedAt = 0L, deleted = false,
    )

    /** 两套都完整的一套数据：各一个孩子、一门课、一笔缴费、两条课次 */
    private fun ledger(): LedgerData {
        val mineChild = child("child-real", "秋天")
        val demoChild = child(DemoIds.CHILD, "小明")
        return LedgerData(
            children = listOf(mineChild, demoChild),
            courses = listOf(
                course("course-real", mineChild.id, "羽毛球"),
                course(DemoIds.COURSE_PIANO, demoChild.id, "钢琴一对一"),
            ),
            payments = listOf(
                payment("pay-real", "course-real"),
                payment("${DemoIds.PREFIX}pay-piano", DemoIds.COURSE_PIANO),
            ),
            lessons = listOf(
                lesson("lesson-real", "course-real"),
                lesson("${DemoIds.PREFIX}lesson-piano", DemoIds.COURSE_PIANO),
            ),
        )
    }

    @Test
    fun `我的数据里没有任何演示记录`() {
        val mine = ledger().forSource(DataSource.MINE)
        assertEquals(listOf("child-real"), mine.children.map { it.id })
        assertEquals(listOf("course-real"), mine.courses.map { it.id })
        assertEquals(listOf("pay-real"), mine.payments.map { it.id })
        assertEquals(listOf("lesson-real"), mine.lessons.map { it.id })
    }

    @Test
    fun `演示视角里没有任何真实记录`() {
        val demo = ledger().forSource(DataSource.DEMO)
        assertEquals(listOf(DemoIds.CHILD), demo.children.map { it.id })
        assertEquals(listOf(DemoIds.COURSE_PIANO), demo.courses.map { it.id })
        assertEquals(listOf("${DemoIds.PREFIX}pay-piano"), demo.payments.map { it.id })
        assertEquals(listOf("${DemoIds.PREFIX}lesson-piano"), demo.lessons.map { it.id })
    }

    @Test
    fun `核销记录 id 不带 seed 前缀 但仍归演示那套`() {
        // settleLessons() 生成的 id 是 "settle-$courseId"，前缀是 settle- 而不是 seed-。
        // 归属只能靠 courseId 判断，否则这条会串到真实账本里、把「剩余课时」算错。
        val data = ledger().let {
            it.copy(lessons = it.lessons + lesson("settle-${DemoIds.COURSE_PIANO}", DemoIds.COURSE_PIANO))
        }
        assertTrue(data.forSource(DataSource.DEMO).lessons.any { it.id == "settle-${DemoIds.COURSE_PIANO}" })
        assertFalse(data.forSource(DataSource.MINE).lessons.any { it.id == "settle-${DemoIds.COURSE_PIANO}" })
    }

    @Test
    fun `在演示孩子名下新建的课 归演示那套`() {
        // saveCourse() 新建时按当前数据源打前缀，这里模拟 id 是普通 UUID 的情形（旧数据/导入）
        val data = ledger().let {
            it.copy(courses = it.courses + course("a-normal-uuid", DemoIds.CHILD, "我自己加的"))
        }
        assertTrue(data.forSource(DataSource.DEMO).courses.any { it.id == "a-normal-uuid" })
        assertFalse(data.forSource(DataSource.MINE).courses.any { it.id == "a-normal-uuid" })
    }

    @Test
    fun `在真实孩子名下新建的课 不会出现在演示视角`() {
        val data = ledger().let {
            it.copy(courses = it.courses + course("another-uuid", "child-real", "新报的游泳"))
        }
        assertTrue(data.forSource(DataSource.MINE).courses.any { it.id == "another-uuid" })
        assertFalse(data.forSource(DataSource.DEMO).courses.any { it.id == "another-uuid" })
    }

    @Test
    fun `改名不改变归属`() {
        // 示例课被改成自己孩子真实的课名，也还是演示那套 —— 归属看 id，不看名字
        val data = ledger().let {
            it.copy(courses = it.courses.map { c ->
                if (c.id == DemoIds.COURSE_PIANO) c.copy(courseName = "羽毛球") else c
            })
        }
        assertFalse(data.forSource(DataSource.MINE).courses.any { it.id == DemoIds.COURSE_PIANO })
        assertEquals(1, data.forSource(DataSource.MINE).courses.size)
    }

    @Test
    fun `清空演示那套之后 我的数据一条不少`() {
        val data = ledger()
        val clearedDemo = data.copy(
            children = data.children.filterNot { DemoIds.isDemo(it.id) },
            courses = data.courses.filterNot { DemoIds.isDemo(it.id) },
            payments = data.payments.filterNot { DemoIds.isDemo(it.id) },
            lessons = data.lessons.filterNot { DemoIds.isDemo(it.id) },
        )
        val mine = clearedDemo.forSource(DataSource.MINE)
        assertEquals(1, mine.children.size)
        assertEquals(1, mine.courses.size)
        assertEquals(1, mine.payments.size)
        assertEquals(1, mine.lessons.size)
        assertEquals(0, clearedDemo.forSource(DataSource.DEMO).courses.size)
    }
}
