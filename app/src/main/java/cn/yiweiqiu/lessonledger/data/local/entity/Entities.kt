package cn.yiweiqiu.lessonledger.data.local.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import kotlinx.serialization.Serializable

/**
 * 所有参与同步的表都必须具备这四个字段：
 * id(UUID，客户端生成) / createdAt / updatedAt / deleted(软删除墓碑)
 */
interface SyncRecord {
    val id: String
    val createdAt: Long
    val updatedAt: Long
    val deleted: Boolean
}

@Serializable
@Entity(tableName = "children")
data class ChildEntity(
    @PrimaryKey override val id: String,
    val name: String = "",
    val nickname: String = "",
    /** yyyy-MM-dd */
    val birthday: String? = null,
    /** 头像底色 #RRGGBB */
    val avatarColor: String = "#FF8A4C",
    val note: String = "",
    override val createdAt: Long = 0,
    override val updatedAt: Long = 0,
    override val deleted: Boolean = false,
) : SyncRecord

@Serializable
@Entity(
    tableName = "courses",
    indices = [Index("childId"), Index("status")],
)
data class CourseEntity(
    @PrimaryKey override val id: String,
    val childId: String = "",
    val orgName: String = "",
    val courseName: String = "",
    /** Category.name */
    val category: String = "OTHER",
    val teacher: String? = null,
    val location: String? = null,
    /** 位掩码 bit0=周一 ... bit6=周日 */
    val weekdayMask: Int = 0,
    /** HH:mm，统一上课时间；下面按天设了时间时，这里当兜底 */
    val startTime: String? = null,
    /**
     * 每个星期几各自的上课时间，JSON：`{"0":"18:00","2":"16:30"}`，key 是 0=周一 ... 6=周日。
     *
     * 一周上好几节课的日子很常见（比如周三放学早 16:30、周六上午 10:00），
     * 最早只有「哪几天 + 一个统一时间」，周三和周六只能共用一个点，排出来的课表是错的。
     * 老数据这个字段是 null，全部回落到 [startTime]。
     */
    val startTimesJson: String? = null,
    /** 单次课时长（分钟），统一值；下面按天设了时长时，这里当兜底 */
    val durationMinutes: Int = 60,
    /**
     * 每个星期几各自的单次课时长（分钟），JSON：`{"0":90,"2":60}`。
     *
     * 同一门课不同时段长度不一样很常见（平时 1 小时、周末 1.5 小时），
     * 只记一个统一时长的话，周末那节课的时长和日历里显示的就是错的。
     */
    val durationMinutesJson: String? = null,
    /** 剩余课时提醒阈值（节） */
    val warningThreshold: Int = 5,
    /** 上课前多少分钟发通知提醒（0 = 不提醒） */
    val remindBeforeMinutes: Int = 30,
    /** CourseStatus.name */
    val status: String = "ACTIVE",
    /**
     * 上一期的课程 id，串起「续费链」。
     *
     * 续费时如果选择了「开新一期」，新课程会指回被续的那条，上一期同时置为已结束。
     * 一条链就是同一门课的第 1、2、3 期；沿这个指针往上走能拿到完整期次，
     * 课程列表靠它把历史期折叠起来，不必靠「机构 + 课程名」这种会被改动的文本去猜。
     * 接续续费（课时累加）不会产生新课程，这个字段自然是 null。
     */
    val previousCourseId: String? = null,
    /** 冗余字段：由缴费记录汇总（单位：半节），只读，不参与用户编辑 */
    val totalLessonsBoughtHalf: Long = 0,
    val note: String = "",
    override val createdAt: Long = 0,
    override val updatedAt: Long = 0,
    override val deleted: Boolean = false,
) : SyncRecord

@Serializable
@Entity(
    tableName = "payments",
    indices = [Index("courseId"), Index("payDate")],
)
data class PaymentEntity(
    @PrimaryKey override val id: String,
    val courseId: String = "",
    /** yyyy-MM-dd */
    val payDate: String = "",
    /** 实付金额（分），退费为负数 */
    val amount: Long = 0,
    /** 原价（分），可空 */
    val originalAmount: Long? = null,
    /** 购买课时（半节） */
    val lessonsBoughtHalf: Long = 0,
    /** 赠送课时（半节） */
    val lessonsBonusHalf: Long = 0,
    /** PaymentKind.name：FULL 一次付清 / DEPOSIT 定金 / BALANCE 尾款 */
    val kind: String = "FULL",
    /**
     * 同一笔购买里，定金与尾款共用的 key（= 定金那笔的 id）。
     * 单笔付清的缴费为 null —— 它自己就是一条完整的批次。
     */
    val groupKey: String? = null,
    /**
     * 定金抵扣金额（分）。活动里「交 500 抵 800」就填 800。
     *
     * 注意它是「定金在总价里当多少钱用」，不是实付：实付在 [amount] 里，
     * 差额就是这单省下的钱。尾款应付 = 原价（下单时的总额）− 抵扣。
     */
    val creditCents: Long = 0,
    /** PayMethod.name */
    val payMethod: String = "WECHAT",
    /** yyyy-MM-dd，空=长期有效 */
    val validUntil: String? = null,
    /** JSON 数组字符串，存本地相对路径 */
    val receiptPaths: String? = null,
    val note: String = "",
    override val createdAt: Long = 0,
    override val updatedAt: Long = 0,
    override val deleted: Boolean = false,
) : SyncRecord

@Serializable
@Entity(
    tableName = "lessons",
    indices = [Index("courseId"), Index(value = ["courseId", "scheduledAt"]), Index("status")],
)
data class LessonEntity(
    @PrimaryKey override val id: String,
    val courseId: String = "",
    /** 计划上课时间 UTC 毫秒 */
    val scheduledAt: Long = 0,
    /** 实际打卡时间 UTC 毫秒 */
    val actualAt: Long? = null,
    val durationMinutes: Int = 60,
    /** LessonStatus.name */
    val status: String = "PENDING",
    /** 本节省扣课时（半节） */
    val deductedHalf: Long = 0,
    /** FIFO 分配的缴费批次（只读，由系统计算） */
    val paymentId: String? = null,
    val teacher: String? = null,
    val note: String = "",
    /** 是否由课表自动生成 */
    val autoGenerated: Boolean = false,
    /**
     * 用户手动删掉过这节自动课次 —— 标记"以后别再自动生成这一天"。
     *
     * 光靠 deleted 不够：删掉后 ensureUpcomingLessons() 会把这一天的课次补回来，
     * 用户"这周不加课"的意思就被无视了。留一个墓碑，重排时跳过即可。
     */
    val suppressed: Boolean = false,
    override val createdAt: Long = 0,
    override val updatedAt: Long = 0,
    override val deleted: Boolean = false,
) : SyncRecord

/** 同步日志，仅本地，不上传 */
@Entity(tableName = "sync_logs")
data class SyncLogEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val at: Long = 0,
    val level: String = "INFO",
    val message: String = "",
)
